package ca.awoo.jray;

public class Colour {
    private final double r, g, b;

    public Colour(double r, double g, double b) {
        this.r = r;
        this.g = g;
        this.b = b;
    }

    public double r(){
        return r;
    }

    public double g(){
        return g;
    }

    public double b(){
        return b;
    }
}
